// Renders the "AI notes" tab (one study note card) and the "Saved" tab.
// Pure rendering: all actions are delegated to handlers supplied by app.js.

import { h, icon, timeAgo } from './dom.js';
import { labelsFor, shortParagraphs } from './note-format.js';

const pageRef = (page, onGo, L = labelsFor('en')) => h('button', {
  class: 'page-ref', type: 'button', title: `Go to page ${page}`, 'aria-label': `Go to page ${page}`,
  onclick: (e) => { e.stopPropagation(); onGo(page); },
}, `${L.page} ${page}`);

function provenanceTag(meta) {
  if (!meta) return null;
  if (meta.simulated) return h('span', { class: 'chip sim', title: 'Hand-written example data, not produced by a model' }, 'Simulated');
  const label = meta.isGemma4 ? `Gemma 4 · ${meta.model}` : meta.model;
  return h('span', { class: 'chip ai', title: `Generated by ${meta.model} via ${meta.runtime}` }, label);
}

function groundingTag(item, L) {
  if (item.grounding === 'unverified') return h('span', { class: 'chip warn', title: 'Treat this part with caution.' }, L.unverified);
  if (item.citedPage) return h('span', { class: 'chip warn', title: `The model cited p. ${item.citedPage}` }, L.corrected);
  if (item.grounding === 'approximate') return h('span', { class: 'chip warn', title: 'Most of the quote matches the PDF text, with small wording differences.' }, L.approximate);
  return null;
}

/** [2,3,4,7] -> "2–4, 7" */
function compactPages(pages) {
  const out = [];
  for (let i = 0; i < pages.length; i++) {
    let j = i;
    while (j + 1 < pages.length && pages[j + 1] === pages[j] + 1) j++;
    out.push(j > i ? `${pages[i]}–${pages[j]}` : String(pages[i]));
    i = j;
  }
  return out.join(', ');
}

/**
 * @param {HTMLElement} root
 * @param {object} s  { hasDoc, note, lastRun, dropped, stats, busy, modelOk, isSample, lang, attention: Map,
 *                      pageStats: Map, excluded: number[], handlers }
 */
export function renderNotes(root, s) {
  const hd = s.handlers;
  root.replaceChildren();
  if (!s.hasDoc) {
    root.append(h('div', { class: 'empty-panel' }, h('strong', {}, 'No document open'), 'Open a PDF or the sample to get started.'));
    return;
  }
  const note = s.note;
  if (!note) {
    root.append(h('div', { class: 'empty-panel' },
      h('strong', {}, 'No study note yet'),
      'Read normally. Select the sentences that matter — they become the most important points — and scroll back to anything you re-read. Then click ',
      h('em', {}, 'Create study note'), '.',
      !s.modelOk ? h('p', { class: 'small' }, 'The model is not available right now. ',
        h('button', { class: 'link-btn', type: 'button', onclick: hd.openSettings }, 'Model setup'),
        s.isSample ? [' · ', h('button', { class: 'link-btn', type: 'button', onclick: hd.startDemo }, 'Try demo mode')] : null) : null,
    ));
    return;
  }

  const L = labelsFor(s.lang);
  const r = s.lastRun;
  const card = h('article', { class: 'note-card', lang: s.lang });

  // ---- header: title, provenance, actions
  card.append(h('header', { class: 'note-card-head' },
    h('div', { class: 'note-chips' },
      provenanceTag(r),
      r && !r.simulated ? h('span', { class: 'chip' }, `${timeAgo(r.generatedAt)} · ${r.durationSeconds}s`) : null,
      s.stats?.total ? h('span', { class: `chip ${s.stats.verified === s.stats.total ? 'ok' : 'warn'}` }, L.verified(s.stats.verified, s.stats.total)) : null,
      r?.repaired ? h('span', { class: 'chip warn', title: 'The first answer was invalid JSON; one repair attempt succeeded.' }, 'repaired') : null,
      s.dropped?.length ? h('span', { class: 'chip warn', title: s.dropped.map((d) => `${d.section}: ${d.reason}`).join('\n') },
        `${s.dropped.length} removed`) : null),
    h('h2', { class: 'note-title' }, note.title),
    h('div', { class: 'note-actions' },
      h('button', { class: 'btn small', type: 'button', onclick: hd.saveNote }, L.save),
      h('button', { class: 'btn small', type: 'button', onclick: hd.copyNote }, L.copy),
      h('button', { class: 'icon-btn small', type: 'button', title: L.regenerate, 'aria-label': L.regenerate, disabled: s.busy, onclick: hd.regenerate }, icon('i-refresh'))),
  ));
  if (r?.simulated) card.append(h('div', { class: 'callout sim' }, L.simulated));

  // ---- highlights: selected (critical) → re-read (high) → key points
  if (note.highlights?.length) {
    card.append(h('section', { class: 'note-block' },
      h('h3', { class: 'note-label' }, L.highlights),
      h('ul', { class: 'hl-list' }, note.highlights.map((hl) => h('li', {
        class: `hl hl-${hl.importance.toLowerCase().replace('_importance', '').replace('_relevance', '')}`,
        title: hl.evidence ? `${L.source}: “${hl.evidence}”` : null,
      },
        h('span', { class: 'hl-dot', 'aria-hidden': 'true' }),
        h('div', { class: 'hl-body' },
          h('span', { class: 'hl-tag' }, L.importance[hl.importance]),
          h('span', { class: `hl-text${hl.fromSelection ? ' quoted' : ''}` }, hl.fromSelection ? `“${hl.text}”` : hl.text),
          ' ', pageRef(hl.page, () => hd.locate(hl.page, hl.evidence), L),
          groundingTag(hl, L)),
      ))),
    ));
  }

  // ---- Summary (collapsible): short overview, then one sub-headed part per section
  const summaryBody = [h('div', { class: 'sum-overview' }, ...shortParagraphs(note.overview, { maxSentences: 3, maxWords: 60 }).map((p) => h('p', {}, p)))];
  for (const sec of note.sections) {
    const stats = s.pageStats?.get(sec.page) ?? {};
    const secs = Math.round(s.attention.get(sec.page) ?? 0);
    summaryBody.push(h('section', { class: `sum-sec depth-${sec.depth}` },
      h('h4', { class: 'sum-h' },
        h('span', { class: 'sum-h-text' }, sec.heading),
        pageRef(sec.page, () => hd.locate(sec.page, sec.evidence), L)),
      h('div', { class: 'note-meta' },
        h('span', { class: `depth-chip ${sec.depth}`, title: 'Detail level follows selections, re-reads and reading time on this page' }, L.depth[sec.depth]),
        stats.selections ? h('span', { class: 'meta-crit' }, L.selectedTimes(stats.selections)) : null,
        stats.rereads ? h('span', { class: 'meta-high' }, L.rereadTimes(stats.rereads)) : null,
        secs >= 10 ? h('span', {}, L.attention(L.duration(secs))) : null,
        groundingTag(sec, L)),
      ...shortParagraphs(sec.content).map((p) => h('p', {}, p)),
      sec.keyPoints.length ? h('ul', { class: 'sum-points', 'aria-label': L.keyPoints }, sec.keyPoints.map((k) => h('li', {}, k))) : null,
    ));
  }
  if (s.excluded?.length) summaryBody.push(h('p', { class: 'note-footnote' }, L.excluded(compactPages(s.excluded))));
  card.append(accordion('summary', L.summary, summaryBody, { open: true, count: note.sections.length }));

  // ---- Sources and reading notes (collapsible)
  const sources = [];
  for (const sec of note.sections) {
    const hasQuote = sec.grounding !== 'unverified' && sec.evidence;
    if (!hasQuote && !sec.readerNote) continue;
    const locate = () => hd.locate(sec.page, sec.evidence);
    sources.push(h('section', { class: `note-section depth-${sec.depth}` },
      h('div', { class: 'note-section-head' }, h('h4', {}, sec.heading), pageRef(sec.page, hd.goToPage, L)),
      hasQuote
        ? h('blockquote', { class: 'note-quote', tabindex: 0, role: 'button', title: `${L.source}: ${L.page} ${sec.page}`,
            onclick: locate, onkeydown: (e) => { if (e.key === 'Enter') locate(); } }, sec.evidence)
        : null,
      sec.readerNote ? h('div', { class: 'note-reader' },
        h('strong', {}, `${L.readerNote}: `), sec.readerNote,
        h('span', { class: 'chip', style: 'margin-left:6px' }, L.signal[sec.signal]),
        sec.wordingFlag ? h('span', { class: 'chip warn', title: 'This wording may read more into your behaviour than the data supports.', style: 'margin-left:4px' }, 'check wording') : null) : null,
    ));
  }
  if (note.reviewLater.length) {
    sources.push(h('section', { class: 'note-section' },
      h('h4', {}, L.review),
      h('ul', { class: 'sum-points' }, note.reviewLater.map((rv) => h('li', {}, pageRef(rv.page, hd.goToPage, L), ' ', rv.reason,
        h('span', { class: 'chip', style: 'margin-left:6px' }, L.signal[rv.signal]))))));
  }
  if (sources.length) card.append(accordion('sources', L.sourcesTitle, sources, { open: false }));

  // ---- Self-test questions (collapsible)
  if (note.questions.length) {
    card.append(accordion('questions', L.questions, [
      h('ol', { class: 'note-questions' }, note.questions.map((q) => {
        const answer = h('div', { class: 'qa-answer', hidden: true }, h('strong', {}, `${L.answer}: `), q.answer);
        const toggle = h('button', { class: 'link-btn small', type: 'button', 'aria-expanded': 'false', onclick: () => {
          answer.hidden = !answer.hidden;
          toggle.textContent = answer.hidden ? L.showAnswer : L.hideAnswer;
          toggle.setAttribute('aria-expanded', String(!answer.hidden));
        } }, L.showAnswer);
        return h('li', {}, q.question, ' ', pageRef(q.page, hd.goToPage, L), h('div', {}, toggle), answer);
      })),
    ], { open: false, count: note.questions.length }));
  }
  card.append(h('p', { class: 'note-footnote' }, L.observation));
  root.append(card);
}

// Open/closed state of each accordion survives re-renders of the panel.
const accordionState = new Map();
let accordionSeq = 0;

/**
 * Accessible accordion with a smooth height transition (CSS grid rows 0fr → 1fr).
 * Collapsed content is `inert`, so it cannot be focused or read out.
 */
function accordion(key, title, children, { open = false, count = null } = {}) {
  const isOpen = accordionState.has(key) ? accordionState.get(key) : open;
  const id = `acc-${key}-${++accordionSeq}`;
  const panel = h('div', { class: 'acc-panel', id, role: 'region', 'aria-labelledby': `${id}-btn`, inert: isOpen ? null : true },
    h('div', { class: 'acc-inner' }, ...children));
  const btn = h('button', { class: 'acc-btn', id: `${id}-btn`, type: 'button', 'aria-expanded': String(isOpen), 'aria-controls': id },
    h('span', { class: 'acc-title' }, title),
    count != null ? h('span', { class: 'acc-count' }, String(count)) : null,
    h('span', { class: 'acc-chevron', 'aria-hidden': 'true' }));
  const wrap = h('section', { class: 'acc', dataset: { open: String(isOpen) } }, h('h3', { class: 'acc-head' }, btn), panel);
  btn.addEventListener('click', () => {
    const next = wrap.dataset.open !== 'true';
    accordionState.set(key, next);
    wrap.dataset.open = String(next);
    btn.setAttribute('aria-expanded', String(next));
    panel.inert = !next;
  });
  return wrap;
}

function noteTags(n) {
  if (n.source === 'manual') return [h('span', { class: 'tag manual' }, 'Your note')];
  if (n.source === 'demo') return [h('span', { class: 'tag sim' }, 'Simulated')];
  return [
    h('span', { class: 'tag ai', title: n.origin?.generatedAt ? `Generated ${timeAgo(n.origin.generatedAt)}` : '' }, `AI · ${n.origin?.model ?? 'model'}`),
    n.edited ? h('span', { class: 'tag edited' }, 'Edited by you') : null,
  ];
}

/**
 * @param {HTMLElement} root
 * @param {object} s  { hasDoc, notes, editingId, isDemo, draftPage, handlers: { goToPage, locateNote, edit, cancelEdit, commitEdit, remove } }
 */
export function renderSaved(root, s) {
  const hd = s.handlers;
  root.replaceChildren();
  if (s.isDemo) root.append(h('div', { class: 'callout sim' }, 'Demo mode: saved notes are kept in memory only and are discarded when you leave demo mode.'));
  if (!s.hasDoc) { root.append(h('div', { class: 'empty-panel' }, h('strong', {}, 'No document open'))); return; }
  if (s.editingId === '__new__') {
    const ta = h('textarea', { 'aria-label': `New note for page ${s.draftPage}`, maxlength: 4000, placeholder: 'Write your note…' });
    root.append(h('article', { class: 'card' },
      h('div', { class: 'card-meta', style: 'margin:0 0 6px' }, h('span', { class: 'tag manual' }, 'New note'), `linked to page ${s.draftPage}`),
      ta,
      h('div', { class: 'card-actions' },
        h('button', { class: 'btn small primary', type: 'button', onclick: () => hd.commitEdit(null, ta.value) }, 'Save'),
        h('button', { class: 'btn small', type: 'button', onclick: hd.cancelEdit }, 'Cancel'))));
    queueMicrotask(() => ta.focus());
  }
  if (!s.notes.length && s.editingId !== '__new__') {
    root.append(h('div', { class: 'empty-panel' }, h('strong', {}, 'No saved notes yet'),
      'Save the study note with “Save note”, select text in the PDF and click “Save as note”, or add your own.'));
    return;
  }
  for (const n of [...s.notes].sort((a, b) => (a.page ?? 1e9) - (b.page ?? 1e9) || (a.createdAt < b.createdAt ? -1 : 1))) {
    if (n.id === s.editingId) {
      const ta = h('textarea', { 'aria-label': 'Note text', maxlength: 20000, style: n.text.length > 600 ? 'min-height:320px' : null }, n.text);
      root.append(h('article', { class: 'card' },
        ta,
        h('div', { class: 'card-actions' },
          h('button', { class: 'btn small primary', type: 'button', onclick: () => hd.commitEdit(n, ta.value) }, 'Save'),
          h('button', { class: 'btn small', type: 'button', onclick: hd.cancelEdit }, 'Cancel'))));
      queueMicrotask(() => ta.focus());
      continue;
    }
    root.append(h('article', {
      class: `card${n.page ? ' clickable' : ''}`, tabindex: n.page ? 0 : null,
      onclick: n.page ? () => hd.locateNote(n) : null,
      onkeydown: n.page ? (e) => { if (e.key === 'Enter' && e.target === e.currentTarget) hd.locateNote(n); } : null,
    },
      h('div', { class: 'card-top' }, h('p', { class: `card-text${n.text.length > 600 ? ' long-note' : ''}`, style: 'white-space: pre-wrap' }, n.text), n.page ? pageRef(n.page, hd.goToPage) : null),
      n.quote ? h('blockquote', { class: 'card-evidence' }, n.quote) : null,
      h('div', { class: 'card-meta' }, ...noteTags(n), h('span', {}, timeAgo(n.updatedAt))),
      h('div', { class: 'card-actions' },
        h('button', { class: 'link-btn', type: 'button', onclick: (e) => { e.stopPropagation(); hd.edit(n); } }, 'Edit'),
        h('button', { class: 'link-btn', type: 'button', onclick: (e) => { e.stopPropagation(); hd.remove(n); } }, 'Delete')),
    ));
  }
}
